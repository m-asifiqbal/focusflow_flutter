/// ============================================================
/// JUDAISM PRESETS — the three services, the Shema, Shabbat, study
/// ============================================================
///
/// What: Modeh Ani, the morning Shema, Shacharit, Mincha and Maariv timed by
/// zmanim (netz, sof zman Shema and Tefillah, chatzot, mincha gedola,
/// shkia, tzeit), tefillin on weekday mornings, the evening and bedtime
/// Shema, Birkat HaMazon, Tehillim, Torah study; and Shabbat: candle
/// lighting 18 minutes before sunset, Kabbalat Shabbat, the Shabbat morning
/// service and Havdalah. Orthodox and Conservative keep the three services
/// and tefillin by default; Reform offers them as options.
/// Why: from the research in docs/prayer_traditions.md (Hebcal and Chabad
/// zmanim; GRA hours; Hebcal's candle-lighting and Havdalah defaults). Each
/// community follows its own luach, so the times are defaults the user can
/// move. The Omer, the fast days, Rosh Chodesh and the festivals follow the
/// Hebrew calendar and arrive with the calendar rules.
/// ============================================================
