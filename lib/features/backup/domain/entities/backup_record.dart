/// ============================================================
/// BACKUP RECORD — one backup made from this device
/// ============================================================
library;

import 'package:flutter/foundation.dart';

/// Stored as [name] in `backup_records.location`.
enum BackupLocation {
  drive,
  local;

  static BackupLocation fromName(String name) =>
      name == 'drive' ? BackupLocation.drive : BackupLocation.local;
}

@immutable
class BackupRecord {
  const BackupRecord({
    required this.id,
    required this.location,
    required this.createdAt,
    this.sizeBytes = 0,
    this.itemCount = 0,
    this.isAuto = false,
    this.isEncrypted = false,
    this.driveFileId,
    this.localPath,
  });

  /// Empty id → a new id is generated by the repository.
  final String id;
  final BackupLocation location;
  final DateTime createdAt;
  final int sizeBytes;
  final int itemCount;

  /// Made by the scheduled auto-backup (vs "Back up now").
  final bool isAuto;

  /// Encrypted with the master-PIN key.
  final bool isEncrypted;
  final String? driveFileId;
  final String? localPath;

  @override
  bool operator ==(Object other) =>
      other is BackupRecord &&
      other.id == id &&
      other.location == location &&
      other.createdAt == createdAt &&
      other.sizeBytes == sizeBytes &&
      other.itemCount == itemCount &&
      other.isAuto == isAuto &&
      other.isEncrypted == isEncrypted &&
      other.driveFileId == driveFileId &&
      other.localPath == localPath;

  @override
  int get hashCode => Object.hash(
    id,
    location,
    createdAt,
    sizeBytes,
    itemCount,
    isAuto,
    isEncrypted,
    driveFileId,
    localPath,
  );

  @override
  String toString() => 'BackupRecord(${location.name}, $createdAt, $itemCount)';
}
