/// Regenerates lib/core/theme/fa_icons.dart from font_awesome_flutter 10.9.1's
/// icon list (FA 6.7.2 — the mockups' icon set).
///
/// Why vendored: font_awesome_flutter 10.x extends `IconData`, which is a
/// `final` class since Flutter 3.44, and 11.x switched to FA 7 glyphs plus a
/// non-IconData wrapper. Bundling the FA 6.7.2 fonts ourselves keeps the
/// exact mockup icons and plain `IconData` constants.
///
/// Usage: `dart run tool/fa_icons/generate.dart <path/to/font_awesome_flutter.dart>`
library;

import 'dart:io';

void main(List<String> args) {
  final source = File(args.single).readAsStringSync();
  // `\s+` also matches definitions dartfmt wrapped onto a second line.
  final pattern = RegExp(
    r'static const IconData (\w+) =\s+IconData(Solid|Regular|Brands)\((0x[0-9a-fA-F]+)\);',
  );
  final out = StringBuffer()
    ..writeln('// GENERATED by tool/fa_icons/generate.dart — do not edit.')
    ..writeln('//')
    ..writeln('// Font Awesome Free 6.7.2 (icons CC BY 4.0, fonts SIL OFL 1.1),')
    ..writeln('// bundled under assets/fonts/fontawesome/. Same names as')
    ..writeln('// font_awesome_flutter 10.x: `FontAwesomeIcons.solidNoteSticky`.')
    ..writeln('// ignore_for_file: public_member_api_docs')
    ..writeln('library;')
    ..writeln()
    ..writeln("import 'package:flutter/widgets.dart';")
    ..writeln()
    ..writeln('const String _solid = \'FontAwesomeSolid\';')
    ..writeln('const String _regular = \'FontAwesomeRegular\';')
    ..writeln('const String _brands = \'FontAwesomeBrands\';')
    ..writeln()
    ..writeln('/// Font Awesome 6.7.2 icons as plain [IconData].')
    ..writeln('abstract final class FontAwesomeIcons {');
  var count = 0;
  for (final m in pattern.allMatches(source)) {
    final family = switch (m[2]) {
      'Solid' => '_solid',
      'Regular' => '_regular',
      _ => '_brands',
    };
    out.writeln(
      '  static const IconData ${m[1]} = IconData(${m[3]}, fontFamily: $family);',
    );
    count++;
  }
  out.writeln('}');
  File('lib/core/theme/fa_icons.dart').writeAsStringSync(out.toString());
  stdout.writeln('Wrote $count icons');
}
