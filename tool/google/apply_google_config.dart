// Applies config/google.json (Google Drive OAuth client ids) to the native
// projects. Run after filling in the file:
//
//   dart run tool/google/apply_google_config.dart
//
// - Validates both ids (`<number>-<hash>.apps.googleusercontent.com`).
// - Writes ios/Flutter/GoogleSignIn.xcconfig with GOOGLE_REVERSED_CLIENT_ID
//   (the iOS id reversed: com.googleusercontent.apps.<number>-<hash>), which
//   Info.plist registers as the URL scheme Google sign-in returns to.
// - Android needs no file: its OAuth client is matched by package name +
//   SHA-1, and the Web id is passed at build time via --dart-define-from-file.
//
// The ids themselves reach Dart through
// `--dart-define-from-file=config/google.json` (GoogleConfig.fromEnvironment).
import 'dart:convert';
import 'dart:io';

const _configPath = 'config/google.json';
const _xcconfigPath = 'ios/Flutter/GoogleSignIn.xcconfig';
final _clientId = RegExp(r'^\d+-[a-z0-9]+\.apps\.googleusercontent\.com$');

void main() {
  final file = File(_configPath);
  if (!file.existsSync()) {
    _fail(
      'Missing $_configPath.\n'
      'Copy config/google.example.json to $_configPath and paste your ids.',
    );
  }
  final Object? json;
  try {
    json = jsonDecode(file.readAsStringSync());
  } on FormatException catch (e) {
    _fail('$_configPath is not valid JSON: ${e.message}');
  }
  if (json is! Map) _fail('$_configPath must be a JSON object.');

  final web =
      (json['GOOGLE_SERVER_CLIENT_ID'] as Object?)?.toString().trim() ?? '';
  final ios =
      (json['GOOGLE_IOS_CLIENT_ID'] as Object?)?.toString().trim() ?? '';

  final problems = <String>[
    if (!_clientId.hasMatch(web))
      'GOOGLE_SERVER_CLIENT_ID must be the *Web application* client id '
          '(…apps.googleusercontent.com), got "$web".',
    if (!_clientId.hasMatch(ios))
      'GOOGLE_IOS_CLIENT_ID must be the *iOS* client id '
          '(…apps.googleusercontent.com), got "$ios".',
    if (web.isNotEmpty && web == ios)
      'The Web and iOS client ids are identical — they must be two different '
          'OAuth clients.',
    if (web.contains('xxxxxxxx') || ios.contains('yyyyyyyy'))
      'Replace the placeholder ids from the example file.',
  ];
  if (problems.isNotEmpty) _fail(problems.map((p) => '• $p').join('\n'));

  final prefix = ios.substring(
    0,
    ios.length - '.apps.googleusercontent.com'.length,
  );
  final reversed = 'com.googleusercontent.apps.$prefix';
  File(_xcconfigPath).writeAsStringSync(
    '// Generated by tool/google/apply_google_config.dart from $_configPath.\n'
    '// Git-ignored. The reversed iOS client id = Google sign-in URL scheme.\n'
    'GOOGLE_REVERSED_CLIENT_ID = $reversed\n',
  );

  stdout.writeln('✓ Google config looks valid.');
  stdout.writeln('✓ Wrote $_xcconfigPath (URL scheme $reversed).');
  stdout.writeln('');
  stdout.writeln('Run / build with the ids:');
  stdout.writeln('  flutter run --dart-define-from-file=$_configPath');
  stdout.writeln(
    '  flutter build appbundle --dart-define-from-file=$_configPath',
  );
  stdout.writeln('  flutter build ipa --dart-define-from-file=$_configPath');
  stdout.writeln('');
  stdout.writeln(
    'Android: make sure the Android OAuth client has package '
    'com.iqballab.focusflow and the SHA-1 of every signing key '
    '(debug, upload, Play app signing).',
  );
}

Never _fail(String message) {
  stderr.writeln('✗ $message');
  exit(1);
}
